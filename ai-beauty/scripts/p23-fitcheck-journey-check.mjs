import fs from 'node:fs';
const issues=[];
const read=p=>fs.readFileSync(p,'utf8');
const fit=read('app/fitcheck/index.tsx');
const tailor=read('app/fitcheck/tailor.tsx');
const entry=read('app/(tabs)/fitcheck-entry.tsx');
const provider=read('src/services/providers/ai/AIProvider.ts');
const validation=read('backend/src/validation.ts');
const ai=read('backend/src/ai.ts');
const media=read('src/state/mediaFlowStore.ts');
if(!/detectedItems: ClosetItemAnalysis\[\]/.test(provider)) issues.push('FitCheckResult lacks structured detectedItems');
if(!/detectedItems: z\.array/.test(validation)) issues.push('backend does not validate detectedItems');
if(!/Do not infer hidden garments/.test(ai)) issues.push('fit-check garment extraction anti-guess rule missing');
if(!/result\.confidence !== "low" && result\.detectedItems/.test(fit)) issues.push('low-confidence result can add detected pieces');
if(!/addClosetItem\(\{ photoUri: null/.test(fit)) issues.push('Fit Check cannot transfer a visible piece to wardrobe safely');
if(/params:\s*\{\s*advice/.test(fit)) issues.push('tailor advice still leaks through route params');
if(!/tailorAdvice: string\[\] \| null/.test(media)) issues.push('ephemeral tailor handoff missing');
if(!/Clipboard\.setStringAsync/.test(tailor) || !/Share\.share/.test(tailor)) issues.push('tailor copy/share actions missing');
if(!/missingTitle/.test(tailor) || !/router\.replace\("\/\(tabs\)\/fitcheck-entry"\)/.test(tailor)) issues.push('invalid tailor route has no recovery CTA');
if(/beauty enhancer first/i.test(entry)) issues.push('Fit Check entry copy still claims enhancer-before-analysis');
if(!/persistUserPhoto/.test(entry)) issues.push('Fit Check capture is not persisted into app-owned storage');
if(/\b\d+(?:[.,]\d+)?\s*(?:cm|mm|inches?|inch|in)\b/i.test(ai)) issues.push('numeric tailor measurement language found in backend Fit Check prompt');
console.log('AI Beauty P23 Fit Check journey gate');
console.log(`blocking_p23_issues=${issues.length}`);
for(const x of issues) console.error(`BLOCKER: ${x}`);
process.exitCode=issues.length?2:0;
