import fs from 'node:fs';
import path from 'node:path';
const root = process.cwd();
const errors = [];
const read = p => fs.readFileSync(path.join(root,p),'utf8');
const db = read('backend/src/db.ts');
const server = read('backend/src/server.ts');
const env = read('backend/.env.example');
if (!/DB_DRIVER=postgres/.test(env)) errors.push('backend .env.example does not document postgres production driver');
if (!/^DATABASE_URL=/m.test(env)) errors.push('backend .env.example does not document DATABASE_URL');
if (!/Production requires DB_DRIVER=postgres/.test(db)) errors.push('production DB fail-closed missing');
if (!/\/v1\/health\/live/.test(server) || !/\/v1\/health\/ready/.test(server)) errors.push('liveness/readiness endpoints missing');
if (!/SIGTERM/.test(server)) errors.push('graceful SIGTERM handling missing');
if (!fs.existsSync(path.join(root,'backend/Dockerfile'))) errors.push('backend Dockerfile missing');
if (!fs.existsSync(path.join(root,'scripts/android-device-smoke.mjs'))) errors.push('android device smoke script missing');
console.log('AI Beauty P16 deployment gate');
for (const e of errors) console.error(`BLOCKER: ${e}`);
console.log(`blocking_p16_deployment_issues=${errors.length}`);
process.exitCode = errors.length ? 2 : 0;
